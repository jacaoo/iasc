import math
from NeuralNetwork import NeuralNetwork


def tanh(x):
    return (math.exp(x) - math.exp(-x)) / (math.exp(x) + math.exp(-x))


def tanh_derivada(x):
    t = tanh(x)
    return 1 - (t ** 2)

def desenhar_para_array(desenho_str):
    # Converte o desenho de texto num array de 784 valores float (0.0 e 1.0)
    array_784 = []
    for linha in desenho_str:
        for char in linha:
            if char == '1':
                array_784.append(1.0)
            else:
                array_784.append(0.0)
    return array_784

